export function orderProposalBibliography(sections, corrections = {}) {
  const result = structuredClone(sections);
  const bibliographyIndex = result.findIndex(section => section.sourceList && /参考文献/.test(section.title));
  if (bibliographyIndex < 0) throw new Error('Cannot locate proposal bibliography.');
  const bibliography = result[bibliographyIndex];
  const records = new Map();
  for (const paragraph of bibliography.paragraphs) {
    const match = paragraph.match(/^\[(\d+)\]\s/);
    if (!match || records.has(Number(match[1]))) throw new Error('Invalid or duplicate bibliography number.');
    records.set(Number(match[1]), paragraph);
  }
  const originalLinks = bibliography.links || [];
  const urls = new Map();
  for (const [label, url] of originalLinks) {
    const match = label.match(/^\[(\d+)\]/);
    if (match && !urls.has(Number(match[1]))) urls.set(Number(match[1]), url);
  }
  const order = [];
  for (const [index, section] of result.entries()) {
    if (index === bibliographyIndex) continue;
    for (const paragraph of section.paragraphs) {
      for (const match of paragraph.matchAll(/\[(\d+)\]/g)) {
        const oldNumber = Number(match[1]);
        if (!records.has(oldNumber) || !urls.has(oldNumber)) throw new Error(`Missing reference or link: ${oldNumber}`);
        if (!order.includes(oldNumber)) order.push(oldNumber);
      }
    }
  }
  const numbers = new Map(order.map((oldNumber, index) => [oldNumber, index + 1]));
  for (const [index, section] of result.entries()) {
    if (index === bibliographyIndex) continue;
    section.paragraphs = section.paragraphs.map(paragraph => paragraph.replace(/\[(\d+)\]/g, (_, oldNumber) => `[${numbers.get(Number(oldNumber))}]`));
  }
  bibliography.paragraphs = order.map(oldNumber => (corrections[oldNumber] || records.get(oldNumber)).replace(/^\[\d+\]/, `[${numbers.get(oldNumber)}]`));
  bibliography.links = order.flatMap((oldNumber, index) => originalLinks
    .filter(([label]) => Number(label.match(/^\[(\d+)\]/)?.[1]) === oldNumber)
    .map(([label, url], linkIndex) => [
      linkIndex === 0 ? bibliography.paragraphs[index] : label.replace(/^\[\d+\]/, `[${index + 1}]`),
      url,
    ]));
  return {sections: result, order, unused: [...records.keys()].filter(number => !numbers.has(number))};
}

