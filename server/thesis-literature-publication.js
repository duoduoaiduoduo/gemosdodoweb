        "科学传播不仅是替换专业词汇，还涉及要解决什么问题、面向谁以及在什么情境中交流。美国国家科学院、工程院和医学院的研究报告指出，传播目标、内容、形式与参与者相互关联，受众的知识、期待和价值判断也会影响其理解；部分目标需要通过公众对话来推进。[6]因此，内容组织不能预设所有公众有相同起点，也不能把增加信息量视为理解必然增加。",
