        "面向公众说明这些概念，需要保留“类别名称—具体对象—判断依据”的关系。介绍一种物质时，应先说清讨论的是整个类别还是其中某一种，再说明为什么受到关注、证据来自何处。以个别物质为例可以使说明更具体，但例子的结论不能直接扩展到全部类别。广义新污染物科普的研究边界，由此应落在帮助公众认识不同问题及其判断条件，而不是把复杂类别压缩为统一的危险标签。",
        "2.1.2 来源、环境过程与暴露条件的说明",
        "来源、环境过程与暴露，回答的是三个相连的问题：物质在哪些活动中产生或使用，释放后经过哪些环境环节，以及人与其他生物如何接触到它。以PFAS为例，相关释放可以发生在生产、产品使用和废弃处置等环节；许多PFAS难以快速降解，部分可随时间积累，饮水、食物或含有相关物质的尘埃等可能成为接触途径。已有研究提示，某些PFAS在一定暴露水平下可能带来生殖发育、免疫等方面的不良影响，但不同物质及暴露水平的证据并不相同，具体暴露也因地点和生活条件而异。[18]因此，提到一种产品用途，并不足以判断某件产品的成分，更不足以判断使用者的健康风险。",
        "POPs进入环境后，能够长时间存在，并随空气、水等介质扩散，也可能在生物体内积累。因此，排放地点与受到影响的地点可能并不一致，相关问题涉及人类健康与生态系统。[19]这一过程提示，理解污染需要从一个地点延伸到更长的时间和更广的空间：既关注物质从哪里释放，也关注它经过哪些环境环节，以及哪些生物可能接触到它。",
        "内分泌干扰物的说明重点，是外源性物质如何模拟、阻断或改变激素系统的正常作用，进而影响生长、发育或生殖等生理过程。相关物质可能涉及部分包装、化妆品或农药等，并通过饮食、空气、皮肤接触等途径进入人体；健康影响的讨论需要结合具体物质及接触时期等条件。[20]公众不应仅凭外观或某一产品类别判断其中存在内分泌干扰物，涉及成分、接触程度和影响的结论仍需相应证据。",
        "抗生素相关环境问题涉及药品生产、人和动物用药，以及废水和废弃物管理等环节。环境中的抗生素残留、耐药微生物和耐药性基因是相互关联但不同的对象。[21]世界卫生组织解释，耐药性涉及细菌等微生物对药物的反应发生变化，使感染更难治疗。[22]科普需要将药物的治疗作用与残留进入环境后的问题分别说明，同时呈现生产排放、废弃物处理等环节的管理责任。",
        "这些例子可以按“来源—释放与迁移—接触途径—可能影响”的顺序组织，帮助公众把几个环节联系起来。其中，危害描述物质能够造成什么影响，暴露涉及接触途径、程度和持续时间，风险则需要结合具体情况评估。国际癌症研究机构在PFOA和PFOS评估问答中说明，致癌分类反映致癌证据的强度，特定暴露情境下的风险还取决于接触条件。[23]所以，“被检出”之后，还需要了解检出的对象、含量和研究条件。把这些区别讲清楚，可以让公众知道资料已经回答了什么，以及哪些判断需要更多信息。",
        "2.1.3 防范与治理建议的适用条件和主体责任",
        "防范建议必须与前述来源和接触条件相对应。若未说明涉及什么物质、何种使用情境和哪一环节，仅给出“避开某类产品”或“改变生活习惯”的结论，公众就难以判断是否适用。产品替代、使用限制和废弃物处置也各有条件，不能把一种措施解释为消除所有相关风险。科普应说明建议由谁发布、针对什么问题，以及个人能够采取行动的范围。",
        "我国《新污染物治理行动方案》将治理安排贯穿调查评估、源头管控、过程减排和末端治理等环节，同时提出科普宣传、绿色消费与公众监督。[4]世界卫生组织关于抗生素生产废水和固体废物管理的指南，则具体面向生产排放问题，为生产者及监管等主体提供指导。[24]这些安排表明，治理不能只落实为个人消费选择：企业需要承担生产、使用、排放及处置环节的责任，公共部门需要组织监测、风险管理和监管，公众则可通过查阅可靠信息、遵循适用要求及参与监督支持治理。",
        "对设计研究而言，行动信息的完整性不仅在于有没有建议，还在于是否讲清建议的依据、适用范围与责任主体。把个人可以参与的事项与企业、公共治理的任务同时呈现，可以避免将系统性的污染问题简化为个人疏忽；当信息不足以支持具体行动时，也应提供进一步查证的方向，而不是用确定的语气补上未经证实的答案。",
        "2.2 参与式交互的设计依据",
        "2.2.1 公众参与、自主选择与个人经验",
        "参与式交互关注公众在接触内容时，是否有提出问题、作出选择和表达理解的机会。参与程度可以不同：有人主要阅读，有人愿意继续查证，也有人希望交流自己的疑问。Jenkins等在参与式文化研究中讨论了表达门槛、创作与分享支持、成员交流及贡献受到重视等条件，并指出成员并不都必须贡献。[7]这一研究处于青年媒介教育语境，本文借此分析新污染物科普的参与条件，关注不同经验的人怎样获得表达与交流的机会。",
